package ee.decathlon_kurm.dto;

public class Kohtunik {

    private String id;
    private String nimi;
    private String riik;

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getNimi() {
        return nimi;
    }

    public void setNimi(String nimi) {
        this.nimi = nimi;
    }

    public String getRiik() {
        return riik;
    }

    public void setRiik(String riik) {
        this.riik = riik;
    }
}