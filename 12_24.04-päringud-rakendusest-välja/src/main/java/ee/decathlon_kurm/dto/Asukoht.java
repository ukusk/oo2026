package ee.decathlon_kurm.dto;

public class Asukoht {

    private String id;
    private String linn;
    private String staadion;

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getLinn() {
        return linn;
    }

    public void setLinn(String linn) {
        this.linn = linn;
    }

    public String getStaadion() {
        return staadion;
    }

    public void setStaadion(String staadion) {
        this.staadion = staadion;
    }
}